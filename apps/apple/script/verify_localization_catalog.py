def _plural_rules(required: str, optional: str = "") -> tuple[frozenset[str], frozenset[str]]:
    required_set = frozenset(required.split())
    # Apple's plural lookup honors an explicit `zero` entry for a count of 0 in
    # every language, so it is always allowed.
    return required_set, required_set | frozenset(optional.split()) | {"zero"}


# The CLDR cardinal plural categories (CLDR 46) that integer counts select in
# each language, as (required, allowed). A plural entry must carry every
# required category and nothing outside the allowed set. The optional `many`
# of Spanish, French, Italian, and Portuguese only covers round millions and
# the optional Hebrew `two` only dual nouns; both fall back to `other` when
# absent. Languages are looked up by full code, then by base code (`zh-Hans`
# uses `zh`). Every shipped language must be declared here, so adding a
# language starts by stating its plural rules.
