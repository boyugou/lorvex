"""Verify Apple string catalogs and source key references.

Every catalog must carry every language declared by any Apple string catalog.
The required language set is discovered from the catalogs themselves so adding
another locale only requires catalog + bundle metadata changes, not verifier
code changes. Every catalog is referenced through native, bundle-qualified
`String(localized:)`, `Text`, and `LocalizedStringResource` calls: the
LorvexApple catalog through `LorvexL10n.bundle`, each module catalog through
its `<Module>L10n.bundle`.

App-Intent metadata (titles, `@Parameter` labels, AppEnum case representations,
and the dialog / confirmation prompts returned from `perform()`) uses the
`LocalizedStringResource("key", … table: … bundle: <Module>L10n.bundle)` form.
Those references are checked for existence against the catalog their `bundle:`
argument names, like every other reference — otherwise a string reached only
through an App Intent could name a key the catalog does not carry and still
pass (it renders in English regardless of the request locale).

No catalog may carry English prose copied into a translation slot, except for
the product and technology names in `IDENTICAL_TRANSLATION_ALLOWLIST`. The App
Shortcuts phrase catalog (`LorvexSystemIntents/Resources/AppShortcuts.xcstrings`)
is keyed by English phrase rather than referenced from Swift, so it is checked
on its own: every phrase, source and translation, names the app exactly once,
and every shipped language translates every phrase.
"""

