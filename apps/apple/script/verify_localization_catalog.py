def _plist_entry_pattern(key: str) -> re.Pattern[str]:
    """A `<key>` line and the string or string-array value that follows it."""
    return re.compile(
        rf"^(?P<indent>[ \t]*)<key>{re.escape(key)}</key>\s*"
        r"(?:<string>[^<]*</string>|<string/>|<array/>|<array>.*?</array>)",
        re.MULTILINE | re.DOTALL,
    )


def _plist_entry_text(key: str, value: str | list[str], indent: str) -> str:
    """`key` and its string or string-array value as plist XML lines at `indent`."""
    if isinstance(value, str):
        return f"{indent}<key>{key}</key>\n{indent}<string>{xml_escape(value)}</string>"
    item_indent = indent + (indent or "\t")
    items = "".join(f"{item_indent}<string>{xml_escape(item)}</string>\n" for item in value)
    return f"{indent}<key>{key}</key>\n{indent}<array>\n{items}{indent}</array>"


def _with_plist_entry(text: str, key: str, value: str | list[str], after: str | None = None) -> str:
    """Plist XML `text` with the top-level `key` set to `value`.

    An existing entry is rewritten where it stands, in its own indentation. A
    missing one is added right after the entry for `after` when the file has
    one, and otherwise at the end of the top-level dict. Every other character
    of `text` is kept.
    """
    existing = _plist_entry_pattern(key).search(text)
    if existing:
        entry = _plist_entry_text(key, value, existing["indent"])
        return text[: existing.start()] + entry + text[existing.end() :]
    anchor = _plist_entry_pattern(after).search(text) if after else None
    if anchor:
        entry = _plist_entry_text(key, value, anchor["indent"])
        return text[: anchor.end()] + "\n" + entry + text[anchor.end() :]
    closing = re.search(r"^[ \t]*</dict>\s*</plist>", text, re.MULTILINE)
    if closing is None:
        raise ValueError("the plist has no top-level dict")
    first_key = re.search(r"^([ \t]*)<key>", text, re.MULTILINE)
    entry = _plist_entry_text(key, value, first_key.group(1) if first_key else "\t")
    return text[: closing.start()] + entry + "\n" + text[closing.start() :]


def sync_plist_localizations(
    path: Path,
    languages: tuple[str, ...],
    source_language: str = DEFAULT_SOURCE_LANGUAGE,
) -> bool:
    """Bring a bundle plist's language metadata in line with the shipped languages.

    Sets `CFBundleLocalizations` to `languages`, and `CFBundleDevelopmentRegion`
    to `source_language` unless it already names it or Xcode's
    `$(DEVELOPMENT_LANGUAGE)`. The file is edited as text, so its comments, key
    order, and formatting stay as written; the edit is parsed back and must
    change exactly those two values, or `ValueError` is raised and nothing is
    written. Returns whether the file changed.
    """
    if not path.is_file():
        return False
    text = path.read_bytes().decode("utf-8")
    value = plistlib.loads(text.encode("utf-8"))
    if not isinstance(value, dict):
        return False

    expected = dict(value)
    allowed_development_regions = {source_language, "$(DEVELOPMENT_LANGUAGE)"}
    if value.get("CFBundleDevelopmentRegion") not in allowed_development_regions:
        expected["CFBundleDevelopmentRegion"] = source_language
        text = _with_plist_entry(text, "CFBundleDevelopmentRegion", source_language)
    if value.get("CFBundleLocalizations") != list(languages):
        expected["CFBundleLocalizations"] = list(languages)
        text = _with_plist_entry(
            text, "CFBundleLocalizations", list(languages), after="CFBundleDevelopmentRegion"
        )
    if expected == value:
        return False

    if plistlib.loads(text.encode("utf-8")) != expected:
        raise ValueError(
            f"{path}: could not update its language keys in place; set "
            f"CFBundleLocalizations to {list(languages)} by hand"
        )
    path.write_bytes(text.encode("utf-8"))
    return True


