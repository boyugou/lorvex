def plural_rules_for(language: str) -> tuple[frozenset[str], frozenset[str]] | None:
    """The (required, allowed) plural categories for `language`, or None."""
    return PLURAL_CATEGORIES.get(language) or PLURAL_CATEGORIES.get(
        re.split(r"[-_]", language, maxsplit=1)[0]
    )


# Plural categories that select a single integer and that a language names in
# the form of the noun itself, so their forms may leave the number out even in
# a substitution, where every other form shows it: Arabic writes one as the
# singular with واحد or واحدة ("مهمة واحدة") and two as the dual ("مهمتان"), and
# Hebrew's optional two is the dual of the nouns that have one ("יומיים").
WORDLESS_COUNT_CATEGORIES: dict[str, frozenset[str]] = {
    "ar": frozenset({"one", "two"}),
    "he": frozenset({"two"}),
}


def wordless_count_categories(language: str) -> frozenset[str]:
    """The plural categories whose forms may leave the number out in `language`."""
    return WORDLESS_COUNT_CATEGORIES.get(language) or WORDLESS_COUNT_CATEGORIES.get(
        re.split(r"[-_]", language, maxsplit=1)[0], frozenset()
    )


def undeclared_plural_language_failures(languages: tuple[str, ...]) -> list[str]:
    return [
        f"shipped language {language!r} has no CLDR plural categories in "
        "PLURAL_CATEGORIES; declare them before shipping its translations"
        for language in languages
        if plural_rules_for(language) is None
    ]


def plural_category_failures(context: str, language: str, plural: dict[str, object]) -> list[str]:
    """Categories `plural` lacks or carries against `language`'s CLDR rules.

    An undeclared language yields nothing here;
    ``undeclared_plural_language_failures`` reports it once.
    """
    rules = plural_rules_for(language)
    if rules is None:
        return []
    required, allowed = rules
    present = set(plural)
    failures: list[str] = []
    missing = sorted(required - present)
    if missing:
        failures.append(f"{context} {language} plural variations missing CLDR categories {missing}")
    unreachable = sorted(present - allowed)
    if unreachable:
        failures.append(
            f"{context} {language} plural variations carry {unreachable}, which "
            f"{language} never selects"
        )
    return failures


# Languages whose CLDR `one` category also selects integers other than 1, and
# which ones. A `one` form there must show the number. French, Hindi, Bengali,
# Persian, and Brazilian Portuguese also use `one` for 0, which an explicit
# `zero` form takes over (Apple's lookup prefers it for a count of 0); Russian
# and Ukrainian also use it for 21, 31, 101, and so on, which nothing takes
# over. An empty value marks a regional variant whose `one` is only 1.
ONE_ALSO_SELECTS: dict[str, str] = {
    "bn": "0",
    "fa": "0",
    "fr": "0",
    "hi": "0",
    "pt": "0",
    "pt-PT": "",
    "ru": "21, 31, 101, …",
    "uk": "21, 31, 101, …",
}
COUNT_PLACEHOLDER = re.compile(r"%(?:\d+\$)?(?:lld|llu|ld|lu|d|u|i)|%arg")


def one_form_failures(context: str, language: str, plural: dict[str, object]) -> list[str]:
    """A `one` form that leaves the number out where `one` is not only 1.

    English and Spanish may write "Once a week" for `one`, because there it
    selects 1 alone; in a language listed in ``ONE_ALSO_SELECTS`` the same form
    would also be shown for 0 or for 21, so it must carry the count.
    """
    also = ONE_ALSO_SELECTS.get(language)
    if also is None:
        also = ONE_ALSO_SELECTS.get(re.split(r"[-_]", language, maxsplit=1)[0], "")
    if not also or (also == "0" and "zero" in plural):
        return []
    variant = plural.get("one")
    unit = variant.get("stringUnit") if isinstance(variant, dict) else None
    text = unit.get("value") if isinstance(unit, dict) else None
    if not isinstance(text, str) or COUNT_PLACEHOLDER.search(text):
        return []
    return [
        f"{context} {language} plural 'one' leaves out the number, but {language} "
        f"also uses 'one' for {also}; show the count"
    ]



# Languages whose typography keeps a number on the same line as the word it
# counts ("5 задач", "3 zadania"): the space after a count placeholder there is
# a no-break space (U+00A0), so a wrapping headline never ends a line on a bare
# number.
BINDS_COUNT_TO_NEXT_WORD = frozenset({"pl", "ru", "uk"})
COUNT_BEFORE_PLAIN_SPACE = re.compile(r"%(?:\d+\$)?(?:lld|llu|ld|lu|d|u|i) (?=[^\W\d_])")


def count_binding_failures(context: str, language: str, localization: object) -> list[str]:
    """Texts in a ``BINDS_COUNT_TO_NEXT_WORD`` language that put a plain space
    between a count placeholder and the word after it, across plain, plural,
    and substitution forms."""
    if language not in BINDS_COUNT_TO_NEXT_WORD:
        return []
    texts: list[str] = []

    def walk(node: object) -> None:
        if isinstance(node, dict):
            unit = node.get("stringUnit")
            if isinstance(unit, dict) and isinstance(unit.get("value"), str):
                texts.append(unit["value"])
            for name, child in node.items():
                if name != "stringUnit":
                    walk(child)

    walk(localization)
    return [
        f"{context} {language} keeps a plain space after a count in {text!r}; "
        "use a no-break space (U+00A0) so the number stays with its word"
        for text in texts
        if COUNT_BEFORE_PLAIN_SPACE.search(text)
    ]

