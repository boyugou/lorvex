def plist_localization_failures(
    path: Path,
    languages: tuple[str, ...],
    source_language: str = DEFAULT_SOURCE_LANGUAGE,
) -> list[str]:
    if not path.is_file():
        return [f"shipping bundle Info.plist missing: {path}"]
    try:
        value = plistlib.loads(path.read_bytes())
    except Exception as error:
        return [f"shipping bundle Info.plist is not valid plist: {path}: {error}"]
    localizations = value.get("CFBundleLocalizations")
    if not isinstance(localizations, list) or not all(isinstance(item, str) for item in localizations):
        return [f"{path} missing CFBundleLocalizations array"]
    actual = tuple(sorted(localizations))
    development_region = value.get("CFBundleDevelopmentRegion")
    allowed_development_regions = {source_language, "$(DEVELOPMENT_LANGUAGE)"}
    if development_region not in allowed_development_regions:
        return [
            f"{path} CFBundleDevelopmentRegion mismatch: "
            f"{development_region!r}; expected {source_language!r}"
        ]
    if actual != languages:
        return [f"{path} CFBundleLocalizations mismatch: {actual}; expected {languages}"]
    return []


def localized_info_plist_values(value: dict[str, object]) -> dict[str, str]:
    """Map each InfoPlist.strings key a bundle needs to its source-language text.

    A top-level key (the bundle names, the calendar permission prompts) is
    localized under its own name, and its source text is the Info.plist value.
    A Home Screen quick action's title is localized under the title itself.
    """
    values: dict[str, str] = {}
    for key in LOCALIZED_INFO_PLIST_KEYS:
        text = value.get(key)
        if isinstance(text, str):
            values[key] = text

    shortcut_items = value.get("UIApplicationShortcutItems")
    if isinstance(shortcut_items, list):
        for item in shortcut_items:
            if not isinstance(item, dict):
                continue
            for key in ["UIApplicationShortcutItemTitle", "UIApplicationShortcutItemSubtitle"]:
                title = item.get(key)
                if isinstance(title, str) and title:
                    values[title] = title
    return values


def localized_info_plist_keys(value: dict[str, object]) -> set[str]:
    return set(localized_info_plist_values(value))


def parse_info_plist_strings(path: Path) -> tuple[dict[str, str], list[str]]:
    if not path.is_file():
        return {}, [f"InfoPlist.strings missing: {path}"]
    text = path.read_text(encoding="utf-8")
    entries: dict[str, str] = {}
    failures: list[str] = []
    pattern = re.compile(r'^\s*("(?:\\.|[^"\\])*")\s*=\s*("(?:\\.|[^"\\])*")\s*;\s*$')

    for line_number, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("//"):
            continue
        match = pattern.match(line)
        if not match:
            failures.append(f"{path}:{line_number} malformed InfoPlist.strings entry")
            continue
        try:
            key = json.loads(match.group(1))
            value = json.loads(match.group(2))
        except json.JSONDecodeError as error:
            failures.append(f"{path}:{line_number} invalid string escape: {error}")
            continue
        if not isinstance(key, str) or not isinstance(value, str):
            failures.append(f"{path}:{line_number} key/value must be strings")
            continue
        entries[key] = value
    return entries, failures


def info_plist_strings_coverage_failures(
    resource_target: str,
    source_values: dict[str, str | None],
    languages: tuple[str, ...],
    config_root: Path = CONFIG_ROOT,
    source_language: str = DEFAULT_SOURCE_LANGUAGE,
) -> list[str]:
    """Check one target's `<language>.lproj/InfoPlist.strings` set.

    Every shipped language localizes every key. The source language's text
    equals the Info.plist's own, because the system shows the strings file
    over the plist value: a drifted English file would replace the reviewed
    text and hand translators a different source. A `None` source text is a
    build-setting value only the build resolves, so only its coverage is
    checked. A directory for a language the app does not ship is rejected,
    because packaging stages every directory and an extra one would make the
    bundle claim that language.
    """
    failures: list[str] = []
    target_root = config_root / "InfoPlist" / resource_target
    for language in languages:
        strings_path = target_root / f"{language}.lproj" / "InfoPlist.strings"
        entries, parse_failures = parse_info_plist_strings(strings_path)
        failures.extend(parse_failures)
        for key, source_text in sorted(source_values.items()):
            localized_value = entries.get(key, "").strip()
            if not localized_value:
                failures.append(f"{strings_path} missing non-empty localization for {key}")
            elif (
                language == source_language and source_text is not None
                and entries[key] != source_text
            ):
                failures.append(
                    f"{strings_path} {key} differs from the Info.plist text: "
                    f"{entries[key]!r}; expected {source_text!r}"
                )
    for directory in sorted(target_root.glob("*.lproj")):
        if directory.name.removesuffix(".lproj") not in languages:
            failures.append(f"{directory} is not a shipped language")
    return failures


def info_plist_strings_failures(
    path: Path,
    languages: tuple[str, ...],
    config_root: Path = CONFIG_ROOT,
    source_language: str = DEFAULT_SOURCE_LANGUAGE,
) -> list[str]:
    if not path.is_file():
        return [f"shipping bundle Info.plist missing: {path}"]
    try:
        value = plistlib.loads(path.read_bytes())
    except Exception as error:
        return [f"shipping bundle Info.plist is not valid plist: {path}: {error}"]
    if not isinstance(value, dict):
        return [f"shipping bundle Info.plist is not a dictionary: {path}"]

    # A background-only agent (LSUIElement + LSBackgroundOnly) never presents its
    # bundle name in any user-visible surface (no Dock tile, menu bar, or window
    # title), so its CFBundleName/DisplayName are technical identifiers, not
    # localized user-facing strings, and need no per-language InfoPlist.strings.
    if value.get("LSUIElement") is True and value.get("LSBackgroundOnly") is True:
        return []

    plist_values = localized_info_plist_values(value)
    if not plist_values:
        return []

    resource_target = INFO_PLIST_RESOURCE_TARGETS.get(path.name)
    if resource_target is None:
        return [f"{path} has localized system-facing strings but no InfoPlist resource target mapping"]

    # XcodeGen names each product after its target, so `$(PRODUCT_NAME)` is
    # the target name; any other build setting is left to the build.
    source_values: dict[str, str | None] = {}
    for key, text in plist_values.items():
        text = re.sub(r"\$[({]PRODUCT_NAME[)}]", resource_target, text)
        source_values[key] = None if re.search(r"\$[({]", text) else text
    return info_plist_strings_coverage_failures(
        resource_target, source_values, languages, config_root, source_language)


def generated_app_info_plist_values(
    script_path: Path = GENERATED_APP_INFO_PLIST_SCRIPT,
    metadata: dict[str, str] | None = None,
) -> tuple[dict[str, str], list[str]]:
    """The localized keys of the macOS app's Info.plist and their English text.

    The macOS app's Info.plist is not checked in: `build_and_run.sh` writes it
    from a heredoc whose values name `app_metadata.sh` variables. This reads
    the heredoc's keys and resolves each `$NAME` against that metadata.
    """
    try:
        text = script_path.read_text(encoding="utf-8")
    except OSError as error:
        return {}, [f"generated Info.plist script unreadable: {script_path}: {error}"]
    heredoc = re.search(r'cat\s*>\s*"\$INFO_PLIST"\s*<<PLIST\n(.*?)\nPLIST\n', text, re.S)
    if heredoc is None:
        return {}, [f"{script_path} has no Info.plist heredoc"]
    resolved_metadata = load_metadata() if metadata is None else metadata

    values: dict[str, str] = {}
    failures: list[str] = []
    for key, raw in re.findall(r"<key>([A-Za-z0-9]+)</key>\s*<string>([^<]*)</string>", heredoc.group(1)):
        if key not in LOCALIZED_INFO_PLIST_KEYS:
            continue
        unknown = [
            name for name in re.findall(r"\$\{?([A-Z_][A-Z0-9_]*)\}?", raw)
            if name not in resolved_metadata
        ]
        if unknown:
            failures.append(f"{script_path} Info.plist {key} names unknown metadata {unknown}")
            continue
        values[key] = re.sub(
            r"\$\{?([A-Z_][A-Z0-9_]*)\}?", lambda match: resolved_metadata[match.group(1)], raw)
    if not values and not failures:
        failures.append(f"{script_path} Info.plist heredoc has no localized keys")
    return values, failures


def generated_info_plist_strings_failures(
    languages: tuple[str, ...],
    source_language: str = DEFAULT_SOURCE_LANGUAGE,
    script_path: Path = GENERATED_APP_INFO_PLIST_SCRIPT,
    config_root: Path = CONFIG_ROOT,
    metadata: dict[str, str] | None = None,
) -> list[str]:
    """Check the macOS app's InfoPlist.strings against its generated Info.plist."""
    source_values, failures = generated_app_info_plist_values(script_path, metadata)
    if source_values:
        failures.extend(info_plist_strings_coverage_failures(
            GENERATED_APP_INFO_PLIST_TARGET, source_values, languages, config_root,
            source_language))
    return failures


