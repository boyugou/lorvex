def _plural_forms(localization: object) -> dict[str, object] | None:
    """The top-level plural variations of a localization, or None."""
    if not isinstance(localization, dict):
        return None
    variations = localization.get("variations")
    plural = variations.get("plural") if isinstance(variations, dict) else None
    return plural if isinstance(plural, dict) and plural else None


def _substitutions(localization: object) -> dict[str, dict[str, object]]:
    if not isinstance(localization, dict):
        return {}
    substitutions = localization.get("substitutions")
    if not isinstance(substitutions, dict):
        return {}
    return {name: value for name, value in substitutions.items() if isinstance(value, dict)}


def _substitution_forms(substitution: dict[str, object]) -> dict[str, object]:
    variations = substitution.get("variations")
    plural = variations.get("plural") if isinstance(variations, dict) else None
    return plural if isinstance(plural, dict) else {}


def _form_text(variant: object) -> str | None:
    unit = variant.get("stringUnit") if isinstance(variant, dict) else None
    text = unit.get("value") if isinstance(unit, dict) else None
    return text if isinstance(text, str) else None


def countless_argument_positions(localization: object) -> frozenset[int]:
    """The arguments whose plural substitution forms all leave the number out.

    Such an argument is a unit word set beside a number the surface shows apart
    from it ("days" under a large "30"); its number only selects the form.
    """
    positions: set[int] = set()
    for substitution in _substitutions(localization).values():
        texts = [_form_text(variant) for variant in _substitution_forms(substitution).values()]
        argument = substitution.get("argNum")
        if texts and isinstance(argument, int) and all(
            isinstance(text, str) and "%arg" not in text for text in texts
        ):
            positions.add(argument)
    return frozenset(positions)


def localization_argument_types(
    localization: object,
) -> tuple[dict[int, str], list[tuple[str, int, str, str]]]:
    """Every argument a localization formats, by position, across all its forms.

    The second value lists each top-level plural form that reads an argument
    with another type than an earlier form: `(category, position, token,
    expected)`.
    """
    arguments: dict[int, str] = {}
    conflicts: list[tuple[str, int, str, str]] = []
    plural = _plural_forms(localization)
    if plural is not None:
        for category, variant in plural.items():
            text = _form_text(variant)
            if text is None:
                continue
            for position, token in format_placeholders(text):
                previous = arguments.get(position)
                if previous is not None and previous != token:
                    conflicts.append((category, position, token, previous))
                else:
                    arguments[position] = token
        return arguments, conflicts
    if isinstance(localization, dict):
        placeholders, _failures = localization_format_placeholders(
            localization, countless_argument_positions(localization))
        for position, token in placeholders:
            arguments.setdefault(position, token)
    return arguments, conflicts


def varied_argument_positions(localization: object) -> set[int]:
    """The arguments whose plural form the localization selects.

    A top-level plural varies by its integer argument; a substitution varies by
    its `argNum`.
    """
    plural = _plural_forms(localization)
    if plural is not None:
        return {
            position
            for variant in plural.values()
            for position, token in format_placeholders(_form_text(variant) or "")
            if token in INTEGER_ARGUMENT_TYPES
        }
    return {
        substitution["argNum"]
        for substitution in _substitutions(localization).values()
        if isinstance(substitution.get("argNum"), int) and _substitution_forms(substitution)
    }


def plural_coverage_failures(key: str, source_language: str, source: object) -> list[str]:
    """Counts in the source text that no plural form agrees with.

    Every integer argument of the source text varies by plural unless
    ``NON_COUNT_INTEGER_ARGUMENTS`` exempts it. A top-level plural covers a text
    with exactly one integer argument; a text with more counts varies each with
    its own substitution.
    """
    arguments, _conflicts = localization_argument_types(source)
    integers = sorted(position for position, token in arguments.items() if token in INTEGER_ARGUMENT_TYPES)
    failures: list[str] = []
    if _plural_forms(source) is not None and len(integers) > 1:
        failures.append(
            f"{key} {source_language} varies by plural at the top level but formats the integer "
            f"arguments {integers}; vary each count with its own substitution"
        )
        return failures
    varied = varied_argument_positions(source)
    exempt = NON_COUNT_INTEGER_ARGUMENTS.get(key, {})
    for position in integers:
        if position not in varied and position not in exempt:
            failures.append(
                f"{key} {source_language} argument {position} is a count (%{arguments[position]}) "
                "with no plural forms; vary it by plural, or list it in "
                "NON_COUNT_INTEGER_ARGUMENTS with the reason it counts nothing"
            )
    return failures


def translation_plural_failures(
    key: str, source_language: str, source: object, language: str, localization: object
) -> list[str]:
    """Arguments the source varies by plural that the translation does not.

    A language with a single plural category writes every count alike, so it
    may use plain text; any other language varies the same arguments.
    """
    rules = plural_rules_for(language)
    if rules is None or rules[0] == frozenset({"other"}):
        return []
    missing = sorted(varied_argument_positions(source) - varied_argument_positions(localization))
    return [
        f"{key} {language} does not vary argument {position} by plural; {source_language} "
        f"does, and {language} has the plural categories {sorted(rules[0])}"
        for position in missing
    ]


def non_count_allowlist_failures(catalogs: list[dict[str, object]]) -> list[str]:
    """Entries of ``NON_COUNT_INTEGER_ARGUMENTS`` that no longer exempt anything."""
    failures: list[str] = []
    for key, exempt in sorted(NON_COUNT_INTEGER_ARGUMENTS.items()):
        sources = []
        for catalog in catalogs:
            strings = catalog.get("strings")
            entry = strings.get(key) if isinstance(strings, dict) else None
            localizations = entry.get("localizations") if isinstance(entry, dict) else None
            if isinstance(localizations, dict) and isinstance(
                localizations.get(catalog_source_language(catalog)), dict
            ):
                sources.append(localizations[catalog_source_language(catalog)])
        if not sources:
            failures.append(f"NON_COUNT_INTEGER_ARGUMENTS names {key!r}, which no catalog has")
            continue
        for source in sources:
            arguments, _conflicts = localization_argument_types(source)
            varied = varied_argument_positions(source)
            for position in sorted(exempt):
                if arguments.get(position) not in INTEGER_ARGUMENT_TYPES or position in varied:
                    failures.append(
                        f"NON_COUNT_INTEGER_ARGUMENTS exempts {key!r} argument {position}, which "
                        "is not an integer argument without plural forms"
                    )
    return failures


def catalog_entry_failures(
    catalog: dict[str, object],
    required_keys: set[str] | None = None,
    languages: tuple[str, ...] = (DEFAULT_SOURCE_LANGUAGE,),
) -> list[str]:
    strings = catalog.get("strings")
    if not isinstance(strings, dict):
        return []

    failures: list[str] = []
    missing_required = sorted((required_keys or set()) - set(strings))
    if missing_required:
        failures.append(f"required localization key(s) missing: {missing_required}")

    for key, value in strings.items():
        if not isinstance(value, dict):
            failures.append(f"{key} entry is not an object")
            continue
        if value.get("extractionState") != "manual":
            failures.append(f"{key} extractionState mismatch: {value.get('extractionState')!r}")
        localizations = value.get("localizations")
        source_language = catalog_source_language(catalog)
        source_localization = (
            localizations.get(source_language) if isinstance(localizations, dict) else None
        )
        # The source text's arguments, across every plural form and
        # substitution, are the entry's ABI: a translation's forms may leave an
        # argument out ("1 record" against "%lld rekord") and may vary by plural
        # where the source text is plain, but never read an argument the source
        # does not pass or read one with another type.
        source_argument_types, source_conflicts = localization_argument_types(source_localization)
        if _plural_forms(source_localization) is not None:
            failures.extend(
                f"{key} {source_language} plural '{category}' changes argument "
                f"{position} type to {token!r}; expected {expected!r}"
                for category, position, token, expected in source_conflicts
            )
        countless = countless_argument_positions(source_localization)
        placeholders_by_language: dict[str, list[tuple[int, str]]] = {}
        for language in languages:
            unit = localizations.get(language) if isinstance(localizations, dict) else None
            plural = _plural_forms(unit)
            failures.extend(count_binding_failures(key, language, unit))
            if plural is not None:
                # Plural-variation entry: every category carries its own
                # stringUnit, and the language must provide CLDR's "other"
                # plus every category its integer counts select. The
                # representative text for placeholder comparison is the
                # "other" form.
                if "other" not in plural:
                    failures.append(f"{key} {language} plural variations missing 'other'")
                failures.extend(plural_category_failures(key, language, plural))
                failures.extend(one_form_failures(key, language, plural))
                for category, variant in plural.items():
                    v_unit = variant.get("stringUnit") if isinstance(variant, dict) else None
                    v_text = v_unit.get("value") if isinstance(v_unit, dict) else None
                    if not isinstance(v_text, str) or not v_text.strip():
                        failures.append(
                            f"{key} {language} plural '{category}' missing stringUnit.value")
                    v_state = v_unit.get("state") if isinstance(v_unit, dict) else None
                    if v_state != "translated":
                        failures.append(
                            f"{key} {language} plural '{category}' state mismatch: {v_state!r}")
                    if isinstance(v_text, str):
                        for position, token in format_placeholders(v_text):
                            expected = source_argument_types.get(position)
                            if expected is None:
                                failures.append(
                                    f"{key} {language} plural '{category}' introduces "
                                    f"unknown argument {position} ({token})"
                                )
                            elif expected != token:
                                failures.append(
                                    f"{key} {language} plural '{category}' argument "
                                    f"{position} type mismatch: {token!r}; expected {expected!r}"
                                )
                other_text = _form_text(plural.get("other"))
                if other_text is not None:
                    placeholders_by_language[language] = format_placeholders(other_text)
            else:
                for name, substitution in _substitutions(unit).items():
                    sub_plural = _substitution_forms(substitution)
                    if sub_plural:
                        failures.extend(
                            plural_category_failures(
                                f"{key} substitution {name!r}", language, sub_plural))
                        if substitution.get("argNum") not in countless:
                            failures.extend(
                                one_form_failures(
                                    f"{key} substitution {name!r}", language, sub_plural))
                string_unit = unit.get("stringUnit") if isinstance(unit, dict) else None
                text = string_unit.get("value") if isinstance(string_unit, dict) else None
                if not isinstance(text, str) or not text.strip():
                    failures.append(f"{key} missing non-empty {language} stringUnit.value")
                else:
                    placeholders, substitution_failures = localization_format_placeholders(
                        unit, countless, wordless_count_categories(language))
                    placeholders_by_language[language] = placeholders
                    failures.extend(
                        f"{key} {language} {failure}" for failure in substitution_failures
                    )
                state = string_unit.get("state") if isinstance(string_unit, dict) else None
                if state != "translated":
                    failures.append(f"{key} {language} stringUnit.state mismatch: {state!r}")
            if language != source_language and isinstance(source_localization, dict) and unit is not None:
                failures.extend(translation_plural_failures(
                    key, source_language, source_localization, language, unit))
        if isinstance(source_localization, dict):
            failures.extend(plural_coverage_failures(key, source_language, source_localization))
        source_placeholders = placeholders_by_language.get(source_language)
        if source_placeholders is not None:
            for language, placeholders in placeholders_by_language.items():
                if language == source_language:
                    continue
                if placeholders != source_placeholders:
                    failures.append(
                        f"{key} {language} format placeholder mismatch: {placeholders}; "
                        f"expected {source_placeholders}"
                    )
    return failures


CJK_NUMBER_UNIT_SPACE = re.compile(r"(?:%(?:\d+\$)?(?:lld|ld|lu|d|u)|%arg|\d) (?=[\u4e00-\u9fff])")


def cjk_number_unit_spacing_failures(catalog: dict[str, object]) -> list[str]:
    """Reject a breaking space between a number and the unit after it in
    Chinese and Japanese localizations, plural and substitution forms included
    (`%arg` is a substitution's number).

    These scripts wrap between any two characters, so the ordinary space that
    sets a number off from its unit or counter ("3 小时", "%lld 项") is also a
    line break opportunity: a line can end on the number and the next start
    with its unit. A no-break space (U+00A0) keeps the gap and binds the pair.
    """
    strings = catalog.get("strings")
    if not isinstance(strings, dict):
        return []

    failures: list[str] = []
    for key, value in strings.items():
        localizations = value.get("localizations") if isinstance(value, dict) else None
        if not isinstance(localizations, dict):
            continue
        for language, localization in localizations.items():
            if not language.startswith(("zh", "ja")) or not isinstance(localization, dict):
                continue
            units = [localization.get("stringUnit")]
            variation_sets = [localization.get("variations") or {}] + [
                substitution.get("variations") or {}
                for substitution in (localization.get("substitutions") or {}).values()
                if isinstance(substitution, dict)
            ]
            for variations in variation_sets:
                for variation in variations.values():
                    if isinstance(variation, dict):
                        units.extend(
                            case.get("stringUnit") for case in variation.values()
                            if isinstance(case, dict)
                        )
            for unit in units:
                text = unit.get("value") if isinstance(unit, dict) else None
                match = CJK_NUMBER_UNIT_SPACE.search(text) if isinstance(text, str) else None
                if match:
                    failures.append(
                        f"{key} {language} breaks between a number and its unit at "
                        f"{match.group(0)!r}; use a no-break space (U+00A0)"
                    )
                    break
    return failures


STRAIGHT_APOSTROPHE = re.compile(r"[A-Za-z]'[A-Za-z]")


def english_typographic_quote_failures(catalog: dict[str, object]) -> list[str]:
    """Reject straight apostrophes and straight double quotes in English values.

    English copy uses the typographic marks Apple's own interface text uses: an
    apostrophe is ’ ("can’t", "today’s") and a quotation is “…” ("Delete
    habit “%@”?"). A straight mark beside a curly one in the same list reads
    as a typo.
    """
    strings = catalog.get("strings")
    if not isinstance(strings, dict):
        return []

    failures: list[str] = []
    for key, value in strings.items():
        localizations = value.get("localizations") if isinstance(value, dict) else None
        localization = localizations.get("en") if isinstance(localizations, dict) else None
        if not isinstance(localization, dict):
            continue
        units = [localization.get("stringUnit")]
        for variation in (localization.get("variations") or {}).values():
            if isinstance(variation, dict):
                units.extend(
                    case.get("stringUnit") for case in variation.values() if isinstance(case, dict)
                )
        for unit in units:
            text = unit.get("value") if isinstance(unit, dict) else None
            if isinstance(text, str) and (STRAIGHT_APOSTROPHE.search(text) or '"' in text):
                failures.append(
                    f"{key} en uses a straight quote mark in {text!r}; use ’ or “…”"
                )
                break
    return failures


def copied_source_translation_failures(
    catalog: dict[str, object],
    languages: tuple[str, ...],
    allowlist: set[str] | frozenset[str] = frozenset(),
) -> list[str]:
    """Reject prose copied verbatim into every non-source localization.

    A single translation may legitimately match English (proper names and
    shared technical vocabulary are common). Requiring *every* shipped locale
    to match the English prose, however, is a reliable signal that a batch
    catalog migration stamped source text into the translation slots. Pure
    placeholder/punctuation templates are excluded because there is no prose
    to translate; intentional product names must be explicitly allowlisted.
    """
    strings = catalog.get("strings")
    if not isinstance(strings, dict):
        return []

    source_language = catalog_source_language(catalog)
    target_languages = tuple(language for language in languages if language != source_language)
    if not target_languages:
        return []

    failures: list[str] = []

    def contains_prose(texts: list[str]) -> bool:
        text = " ".join(texts)
        text = re.sub(r"%(?:(?:\d+)\$)?#@[A-Za-z0-9_]+@", "", text)
        text = text.replace("%arg", "")
        text = re.sub(
            r"%(?:(?:\d+)\$)?(?:[-+#0 ]*\d*(?:\.\d+)?)?"
            r"(?:hh|h|ll|l|L|z|t|j)?[@diuoxXfFeEgGaAcCsSp]",
            "",
            text,
        )
        return re.search(r"[A-Za-z]", text) is not None

    for key, entry_value in strings.items():
        if key in allowlist or not isinstance(entry_value, dict):
            continue
        localizations = entry_value.get("localizations")
        if not isinstance(localizations, dict):
            continue
        source = localizations.get(source_language)
        source_plural = (
            source.get("variations", {}).get("plural")
            if isinstance(source, dict)
            else None
        )
        if isinstance(source_plural, dict) and source_plural:
            source_forms = {
                category: variant.get("stringUnit", {}).get("value")
                for category, variant in source_plural.items()
                if isinstance(variant, dict)
            }
            if not all(isinstance(text, str) for text in source_forms.values()):
                continue
            source_other = source_forms.get("other")
            if not isinstance(source_other, str) or not contains_prose(list(source_forms.values())):
                continue

            copied = True
            for language in target_languages:
                target = localizations.get(language)
                target_plural = (
                    target.get("variations", {}).get("plural")
                    if isinstance(target, dict)
                    else None
                )
                if not isinstance(target_plural, dict) or not target_plural:
                    # A language without plural forms may carry one plain
                    # string; copying any English form into it is still a copy.
                    target_unit = target.get("stringUnit") if isinstance(target, dict) else None
                    target_text = target_unit.get("value") if isinstance(target_unit, dict) else None
                    if target_text not in source_forms.values():
                        copied = False
                        break
                    continue
                for category, variant in target_plural.items():
                    unit = variant.get("stringUnit") if isinstance(variant, dict) else None
                    target_text = unit.get("value") if isinstance(unit, dict) else None
                    expected = source_forms.get(category, source_other)
                    if not isinstance(target_text, str) or target_text != expected:
                        copied = False
                        break
                if not copied:
                    break
            if copied:
                failures.append(
                    f"{key} copies source-language prose into every non-source localization"
                )
            continue

        source_substitutions = (
            source.get("substitutions") if isinstance(source, dict) else None
        )
        if isinstance(source_substitutions, dict) and source_substitutions:
            source_unit = source.get("stringUnit")
            source_outer = (
                source_unit.get("value") if isinstance(source_unit, dict) else None
            )
            source_substitution_forms: dict[str, dict[str, str]] = {}
            for name, substitution in source_substitutions.items():
                plural = (
                    substitution.get("variations", {}).get("plural")
                    if isinstance(substitution, dict)
                    else None
                )
                if not isinstance(plural, dict) or not plural:
                    source_substitution_forms = {}
                    break
                forms: dict[str, str] = {}
                for category, variant in plural.items():
                    unit = variant.get("stringUnit") if isinstance(variant, dict) else None
                    text = unit.get("value") if isinstance(unit, dict) else None
                    if not isinstance(text, str):
                        forms = {}
                        break
                    forms[category] = text
                if not forms or "other" not in forms:
                    source_substitution_forms = {}
                    break
                source_substitution_forms[name] = forms

            source_leaf_texts = [
                text
                for forms in source_substitution_forms.values()
                for text in forms.values()
            ]
            if (
                isinstance(source_outer, str)
                and source_substitution_forms
                and contains_prose([source_outer, *source_leaf_texts])
            ):
                copied = True
                for language in target_languages:
                    target = localizations.get(language)
                    target_unit = target.get("stringUnit") if isinstance(target, dict) else None
                    target_outer = (
                        target_unit.get("value") if isinstance(target_unit, dict) else None
                    )
                    target_substitutions = (
                        target.get("substitutions") if isinstance(target, dict) else None
                    )
                    if target_outer != source_outer or not isinstance(
                        target_substitutions, dict
                    ):
                        copied = False
                        break
                    for name, source_forms in source_substitution_forms.items():
                        target_substitution = target_substitutions.get(name)
                        target_plural = (
                            target_substitution.get("variations", {}).get("plural")
                            if isinstance(target_substitution, dict)
                            else None
                        )
                        if not isinstance(target_plural, dict) or not target_plural:
                            copied = False
                            break
                        for category, variant in target_plural.items():
                            unit = (
                                variant.get("stringUnit")
                                if isinstance(variant, dict)
                                else None
                            )
                            target_text = unit.get("value") if isinstance(unit, dict) else None
                            expected = source_forms.get(category, source_forms["other"])
                            if not isinstance(target_text, str) or target_text != expected:
                                copied = False
                                break
                        if not copied:
                            break
                    if not copied:
                        break
                if copied:
                    failures.append(
                        f"{key} copies source-language prose into every non-source localization"
                    )
                continue

        source_unit = source.get("stringUnit") if isinstance(source, dict) else None
        source_text = source_unit.get("value") if isinstance(source_unit, dict) else None
        if not isinstance(source_text, str) or not contains_prose([source_text]):
            continue

        target_values: list[str] = []
        for language in target_languages:
            localization = localizations.get(language)
            string_unit = (
                localization.get("stringUnit") if isinstance(localization, dict) else None
            )
            value = string_unit.get("value") if isinstance(string_unit, dict) else None
            if not isinstance(value, str):
                target_values = []
                break
            target_values.append(value)
        if target_values and all(value == source_text for value in target_values):
            failures.append(
                f"{key} copies source-language prose into every non-source localization"
            )
    return failures


def app_shortcut_phrase_failures(
    catalog: dict[str, object],
    languages: tuple[str, ...],
) -> list[str]:
    """Check the App Shortcuts phrase catalog, which Swift never references by key.

    App Intents requires every phrase to name the app exactly once, through the
    literal `${applicationName}` token, in the source phrase (the catalog key)
    and in each translation. Every shipped language must translate every
    phrase: an English phrase left in a translation slot is a voice trigger no
    speaker of that language says.
    """
    strings = catalog.get("strings")
    if not isinstance(strings, dict):
        return ["AppShortcuts.xcstrings has no strings table"]
    source_language = catalog_source_language(catalog)
    failures: list[str] = []
    for phrase, entry in strings.items():
        if phrase.count(APP_NAME_TOKEN) != 1:
            failures.append(f"App Shortcut phrase {phrase!r} must contain {APP_NAME_TOKEN} exactly once")
        localizations = entry.get("localizations") if isinstance(entry, dict) else None
        if not isinstance(localizations, dict):
            localizations = {}
        for language in languages:
            if language == source_language:
                continue
            localization = localizations.get(language)
            unit = localization.get("stringUnit") if isinstance(localization, dict) else None
            value = unit.get("value") if isinstance(unit, dict) else None
            if not isinstance(value, str) or not value.strip():
                failures.append(f"App Shortcut phrase {phrase!r} has no {language} translation")
            elif value == phrase:
                failures.append(f"App Shortcut phrase {phrase!r} copies English into {language}")
            elif value.count(APP_NAME_TOKEN) != 1:
                failures.append(
                    f"App Shortcut phrase {phrase!r} ({language}) must contain {APP_NAME_TOKEN} exactly once"
                )
    return failures


def referenced_app_keys(source_roots: list[Path] = SOURCE_ROOTS) -> set[str]:
    keys: set[str] = set()
    native_by_token = native_localized_string_bundle_keys(source_roots)
    for token in APP_NATIVE_BUNDLE_TOKENS:
        keys |= native_by_token.get(token, set())
    native_text_by_token = native_localized_text_bundle_keys(source_roots)
    for token in APP_NATIVE_BUNDLE_TOKENS:
        keys |= native_text_by_token.get(token, set())
    keys |= bundle_owned_resource_keys(APP_RESOURCE_BUNDLE_TOKENS, source_roots)
    return keys


def source_reference_failures(
    catalog: dict[str, object],
    source_roots: list[Path] = SOURCE_ROOTS,
) -> list[str]:
    catalog_key_set = catalog_keys(catalog)
    referenced_keys = referenced_app_keys(source_roots)
    missing = sorted(referenced_keys - catalog_key_set)
    if missing:
        return [f"source references localization key(s) missing from catalog: {missing}"]
    return []


# Reverse of the missing-key check: every catalog key must be referenced
# somewhere in the app (or allowlisted in REQUIRED_KEYS), so dead keys can't
# accumulate undetected. Scans the WHOLE tree — Sources (every module, not just
# the four primary app surfaces) plus Tests — so a key used only
# in a widget, the core, or a test is never falsely flagged.
DEAD_KEY_SCAN_ROOTS = [ROOT / "Sources", ROOT / "Tests"]


def unreferenced_app_key_failures(
    catalog: dict[str, object], source_roots: list[Path] = DEAD_KEY_SCAN_ROOTS
) -> list[str]:
    referenced = referenced_app_keys(source_roots)
    dead = sorted(catalog_keys(catalog) - referenced - REQUIRED_KEYS)
    if dead:
        return [
            "catalog has unreferenced key(s) (not used via an app-owned native lookup "
            f"or resource and not in REQUIRED_KEYS): {dead}"
        ]
    return []


def unreferenced_module_key_failures(
    helper: str,
    catalog: dict[str, object],
    source_roots: list[Path] = DEAD_KEY_SCAN_ROOTS,
) -> list[str]:
    referenced = module_owned_reference_keys(helper, source_roots)
    dead = sorted(catalog_keys(catalog) - referenced - MODULE_REQUIRED_KEYS.get(helper, set()))
    if dead:
        return [
            f"{helper} catalog has unreferenced key(s) "
            f"(not used via a native lookup or bundle-owned resource): {dead}"
        ]
    return []


def referenced_module_keys(helper: str, source_roots: list[Path]) -> set[str]:
    """Literal keys of the `String(localized:)` and `Text` calls under
    `source_roots` whose `bundle:` is one of the module's tokens."""
    keys: set[str] = set()
    native_by_token = native_localized_string_bundle_keys(source_roots)
    for token in NATIVE_STRING_BUNDLE_TOKENS.get(helper, set()):
        keys |= native_by_token.get(token, set())
    native_text_by_token = native_localized_text_bundle_keys(source_roots)
    for token in NATIVE_STRING_BUNDLE_TOKENS.get(helper, set()):
        keys |= native_text_by_token.get(token, set())
    return keys


def module_reference_failures(
    helper: str, catalog: dict[str, object], source_roots: list[Path]
) -> list[str]:
    missing = sorted(referenced_module_keys(helper, source_roots) - catalog_keys(catalog))
    if missing:
        return [f"{helper} references key(s) missing from its catalog: {missing}"]
    return []


