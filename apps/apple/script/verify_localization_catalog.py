# --- Code default vs catalog `en` equality gate -----------------------------
#
# Every literal-default lookup resolves a key through its owning catalog, and
# the catalog value always wins over the code's `defaultValue`. If the two drift
# apart, the app ships the catalog copy while reviewers reading the call site see
# something else. This gate covers native `String(localized:)` and deferred
# `LocalizedStringResource` calls, each against the catalog its `bundle:` names.
# An interpolated default is compared with the catalog's `en` text placeholder
# for placeholder (a plural entry through its `other` form, each substitution
# through its `other` form). A default that concatenates a non-literal is
# skipped, since its text is not known, and so is an entry whose substitution
# forms leave the number out (a unit word shown beside a number displayed apart
# from it), since its default carries a number its catalog text does not show.

DEFAULT_VALUE_SOURCE_ROOTS = [ROOT / "Sources"]
# A decoded literal shows each `\(…)` interpolation as INTERPOLATION_MARK, and a
# `+` operand that is not a literal as NON_LITERAL_MARK, so an interpolated
# default value can be compared with its catalog text placeholder for
# placeholder, and a computed one is recognized as not comparable.
INTERPOLATION_MARK = "\ufffc"
NON_LITERAL_MARK = "\ufffd"


def _parse_swift_string(text: str, pos: int) -> tuple[str, bool, int] | None:
    """Decode the Swift string literal at/after `pos`. Returns
    (value, has_interpolation, end_index) or None when no literal is present;
    each interpolation appears in `value` as INTERPOLATION_MARK. Handles
    single-line and `\"\"\"` multiline literals (indentation strip and
    `\\`-newline line continuation)."""
    n = len(text)
    while pos < n and text[pos] in " \t\r\n":
        pos += 1
    if pos >= n or text[pos] != '"':
        return None
    if text[pos:pos + 3] == '"""':
        pos += 3
        start = pos
        while pos < n and text[pos:pos + 3] != '"""':
            pos += 1
        if pos >= n:
            return None
        raw = text[start:pos]
        end_pos = pos + 3
        lines = raw.split("\n")
        indent = lines[-1]
        body = lines[1:-1] if len(lines) >= 2 else []
        stripped = [
            line[len(indent):] if line.startswith(indent) else line.lstrip()
            for line in body
        ]
        joined = "\n".join(stripped)
        return _decode_escapes(joined, multiline=True) + (end_pos,)
    pos += 1
    buf: list[str] = []
    interp = False
    while pos < n:
        c = text[pos]
        if c == '"':
            return "".join(buf), interp, pos + 1
        if c == "\n":
            return None
        if c == "\\":
            nxt = text[pos + 1] if pos + 1 < n else ""
            if nxt == "(":
                interp = True
                buf.append(INTERPOLATION_MARK)
                depth = 0
                pos += 1
                while pos < n:
                    if text[pos] == "(":
                        depth += 1
                    elif text[pos] == ")":
                        depth -= 1
                        if depth == 0:
                            pos += 1
                            break
                    pos += 1
                continue
            decoded, advance = _decode_escape_char(text, pos)
            buf.append(decoded)
            pos += advance
            continue
        buf.append(c)
        pos += 1
    return None


def _decode_escape_char(text: str, pos: int) -> tuple[str, int]:
    """Decode a single backslash escape at `text[pos]`; returns (char, length)."""
    nxt = text[pos + 1] if pos + 1 < len(text) else ""
    simple = {"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'", "0": "\0"}
    if nxt in simple:
        return simple[nxt], 2
    if nxt == "u" and text[pos + 2:pos + 3] == "{":
        end = text.index("}", pos + 3)
        return chr(int(text[pos + 3:end], 16)), end + 1 - pos
    return nxt, 2


def _decode_escapes(body: str, multiline: bool) -> tuple[str, bool]:
    out: list[str] = []
    interp = False
    i = 0
    m = len(body)
    while i < m:
        c = body[i]
        if c == "\\":
            nxt = body[i + 1] if i + 1 < m else ""
            if nxt == "(":
                interp = True
                out.append(INTERPOLATION_MARK)
                depth = 0
                i += 1
                while i < m:
                    if body[i] == "(":
                        depth += 1
                    elif body[i] == ")":
                        depth -= 1
                        if depth == 0:
                            i += 1
                            break
                    i += 1
                continue
            if multiline and nxt == "\n":
                i += 2
                continue
            decoded, advance = _decode_escape_char(body, i)
            out.append(decoded)
            i += advance
            continue
        out.append(c)
        i += 1
    return "".join(out), interp


def _parse_concat_string(text: str, pos: int) -> tuple[str, bool, int] | None:
    """Parse a possibly `"a" + "b" + …` literal; a non-literal operand sets the
    interpolation flag and ends `value` with NON_LITERAL_MARK, since the text is
    then not known."""
    first = _parse_swift_string(text, pos)
    if first is None:
        return None
    value, interp, end = first
    while True:
        match = re.match(r"\s*\+\s*", text[end:])
        if not match:
            break
        nxt = _parse_swift_string(text, end + match.end())
        if nxt is None:
            return value + NON_LITERAL_MARK, True, end
        v2, i2, e2 = nxt
        value += v2
        interp = interp or i2
        end = e2
    return value, interp, end


def _catalog_en_values(catalog: dict[str, object]) -> dict[str, str]:
    """Plain `en` stringUnit values by key; plural-only entries are omitted."""
    out: dict[str, str] = {}
    strings = catalog.get("strings")
    if not isinstance(strings, dict):
        return out
    for key, entry in strings.items():
        if not isinstance(entry, dict):
            continue
        en = entry.get("localizations", {}).get("en") if isinstance(entry.get("localizations"), dict) else None
        value = en.get("stringUnit", {}).get("value") if isinstance(en, dict) else None
        if isinstance(value, str):
            out[key] = value
    return out


PRINTF_PLACEHOLDER = re.compile(
    r"%(?:\d+\$)?(?:[-+#0 ]*\d*(?:\.\d+)?)?(?:hh|h|ll|l|L|z|t|j)?[@diuoxXfFeEgGaAcCsSp]"
)
SUBSTITUTION_MARKER = re.compile(r"%(?:\d+\$)?#@([A-Za-z0-9_]+)@")


def _marked_template(text: str) -> str:
    """`text` with each printf placeholder as INTERPOLATION_MARK and `%%` as `%`:
    the form an interpolated Swift default value of the same text decodes to."""
    parts = text.split("%%")
    return "%".join(PRINTF_PLACEHOLDER.sub(INTERPOLATION_MARK, part) for part in parts)


def _catalog_en_templates(catalog: dict[str, object]) -> dict[str, str]:
    """The `en` text of each entry as an interpolated default value states it.

    A plural entry reads as its `other` form, and each substitution marker as
    its substitution's `other` form with `%arg` as the argument. An entry whose
    substitution forms leave the number out (a unit word shown beside a number
    displayed apart from it) has no template, since its default value carries
    a number its catalog text does not show.
    """
    out: dict[str, str] = {}
    strings = catalog.get("strings")
    if not isinstance(strings, dict):
        return out
    for key, entry in strings.items():
        localizations = entry.get("localizations") if isinstance(entry, dict) else None
        en = localizations.get("en") if isinstance(localizations, dict) else None
        if not isinstance(en, dict):
            continue
        plural = en.get("variations", {}).get("plural") if isinstance(en.get("variations"), dict) else None
        if isinstance(plural, dict):
            other = plural.get("other", {}).get("stringUnit", {}).get("value")
            if isinstance(other, str):
                out[key] = _marked_template(other)
            continue
        value = en.get("stringUnit", {}).get("value") if isinstance(en.get("stringUnit"), dict) else None
        if not isinstance(value, str):
            continue
        substitutions = en.get("substitutions") if isinstance(en.get("substitutions"), dict) else {}
        countless = False

        def expand(match: re.Match[str]) -> str:
            nonlocal countless
            substitution = substitutions.get(match.group(1)) or {}
            forms = substitution.get("variations", {}).get("plural", {})
            texts = [form.get("stringUnit", {}).get("value", "") for form in forms.values()]
            if any("%arg" not in text for text in texts):
                countless = True
            other = forms.get("other", {}).get("stringUnit", {}).get("value", "")
            return other.replace("%arg", "\0ARG\0")

        expanded = SUBSTITUTION_MARKER.sub(expand, value)
        if countless:
            continue
        out[key] = _marked_template(expanded).replace("\0ARG\0", INTERPOLATION_MARK)
    return out


def _bundle_call_site_defaults(
    source_roots: list[Path],
    opener: re.Pattern[str],
    bundle_tokens: set[str],
) -> list[tuple[str, str, Path, int]]:
    """Extract key/default pairs from calls owned by `bundle_tokens`; an
    interpolated default carries its INTERPOLATION_MARKs."""
    results: list[tuple[str, str, Path, int]] = []
    for root in source_roots:
        if not root.exists():
            continue
        for path in sorted(root.rglob("*.swift")):
            text = read_swift_source(path)
            for _key, token, body, start in _iter_keyed_localization_call_details(
                text, opener
            ):
                if token not in bundle_tokens:
                    continue
                key_parsed = _parse_swift_string(body, 0)
                if key_parsed is None:
                    continue
                key, key_interp, key_end = key_parsed
                if key_interp:
                    continue
                separator = re.match(
                    r"\s*,\s*defaultValue\s*:\s*", body[key_end:]
                )
                if separator is None:
                    continue
                default_parsed = _parse_concat_string(
                    body, key_end + separator.end()
                )
                if default_parsed is None:
                    continue
                default, _, _ = default_parsed
                line = text.count("\n", 0, start) + 1
                results.append((key, default, path, line))
    return results


